#ifndef INCLUDE_GUARD_ARENE_BASE_ARENE_BASE_TESTING_DETAIL_PROPERTY_TRAMPOLINE_HPP_
#define INCLUDE_GUARD_ARENE_BASE_ARENE_BASE_TESTING_DETAIL_PROPERTY_TRAMPOLINE_HPP_

#include "arene/base/functional/function_traits.hpp"
#include "arene/base/stdlib_choice/move.hpp"
#include "arene/base/testing/detail/any_prng_ref.hpp"
#include "arene/base/type_list/type_list.hpp"

namespace arene {
namespace base {
namespace testing {
namespace detail {

/// @brief adapts a property closure for use with @c run_property
/// @tparam Closure property closure type, typically synthesized by
///   @c ARENE_PROPERTY
///
/// @c ::arene::base::testing::run_property inspects its callable's
/// @c operator() to discover the argument types it needs to generate, then
/// invokes the callable with a PRNG reference followed by the generated
/// values. A property closure synthesized by @c ARENE_PROPERTY does not
/// match this convention directly: it takes the PRNG as a data member
/// (exposed as @c prng within the user's brace-scope body) and its
/// @c operator() parameters are only the user-specified generated
/// arguments. @c property_trampoline bridges the two by constructing the
/// closure with the PRNG reference and forwarding the remaining generated
/// values to its @c operator().
template <class Closure, class = member_function_arguments_t<decltype(&Closure::operator())>>
struct property_trampoline;

/// @brief adapts a property closure to allow use with @c run_property
/// @tparam Closure property closure type
/// @tparam Args user-specified closure argument types
template <class Closure, class... Args>
struct property_trampoline<Closure, ::arene::base::type_list<Args...>> {
  /// @brief construct the closure and invoke it with the generated arguments
  /// @param prng PRNG reference supplied by the property runner
  /// @param args values generated by the runner
  ///
  /// @note @c operator() must be a non-template member function to allow
  /// deduction of function arguments. The PRNG type is erased behind
  /// @c any_prng_ref so the trampoline need not know it a priori.
  auto operator()(any_prng_ref prng, Args... args) const -> void { Closure{prng}(std::move(args)...); }
};

}  // namespace detail
}  // namespace testing
}  // namespace base
}  // namespace arene
#endif  // INCLUDE_GUARD_ARENE_BASE_ARENE_BASE_TESTING_DETAIL_PROPERTY_TRAMPOLINE_HPP_
